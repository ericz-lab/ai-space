export type Lang = "en" | "zh";
const TABLES: Record<Lang, Record<Key, string>> = { en, zh };

/** The client's language from the desktop's preferred languages, `en` unless the first known one is Chinese. */
export function detectLang(names: readonly string[]): Lang {
  for (const n of names) {
    const tag = n.toLowerCase();
    if (tag.startsWith("zh")) return "zh";
    if (tag.startsWith("en") || tag === "c" || tag === "posix") return "en";
  }
  return "en";
}

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return TABLES[lang][key].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

